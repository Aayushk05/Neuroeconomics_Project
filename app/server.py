"""Survey server: serves the single-page survey and stores completed responses.

    python app/server.py                  # http://localhost:5050  (?pilot=1 for pilot runs)

Nothing about a participant is stored until they submit at the end, as the
consent page promises. /api/start only hands out a screen plan and carries no
personal data; the only trace of someone who stops early is that plan.

Environment:
    DATABASE_URL  Neon/Postgres connection string (required on Vercel)
    SURVEY_DB     optional local SQLite file path (default app/data/survey.sqlite3)
    EXPORT_TOKEN  enables GET /api/export.zip with "Authorization: Bearer <token>"
    PORT          port for the development server (default 5050)
"""
import csv
import io
import json
import os
import random
import secrets
import sqlite3
import zipfile
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path

from flask import Flask, Response, abort, jsonify, request, send_from_directory

try:  # Vercel imports app.server; direct local execution imports server.
    from .export import csv_texts
    from .schema import Invalid, validate
except ImportError:
    from export import csv_texts
    from schema import Invalid, validate

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SURVEY = ROOT / "survey"
DESIGN_SLOTS = [1, 2, 3, 5, 6, 7, 8, 10]       # screens 4 and 9 are the attention checks
IN_PROGRESS_WINDOW = timedelta(minutes=30)     # unfinished starts this recent count toward block balance
CODE_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
RNG = random.SystemRandom()

SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY, block INTEGER NOT NULL, pilot INTEGER NOT NULL,
    plan TEXT NOT NULL, started_at TEXT NOT NULL, completed_at TEXT);
CREATE TABLE IF NOT EXISTS participants (
    pid INTEGER PRIMARY KEY AUTOINCREMENT, token TEXT UNIQUE NOT NULL, code TEXT UNIQUE NOT NULL,
    pilot INTEGER NOT NULL, block INTEGER NOT NULL, answers TEXT NOT NULL, submitted_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS choices (
    pid INTEGER NOT NULL REFERENCES participants(pid), block INTEGER, set_id INTEGER, kind TEXT,
    pair INTEGER, alt_id INTEGER, flipped INTEGER, chosen INTEGER, salary_level REAL, salary REAL,
    varpay TEXT, arrangement TEXT, hours INTEGER, autonomy TEXT, growth TEXT, rt_ms INTEGER);
"""

POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY, block INTEGER NOT NULL, pilot SMALLINT NOT NULL CHECK (pilot IN (0, 1)),
    plan TEXT NOT NULL, started_at TEXT NOT NULL, completed_at TEXT);
CREATE TABLE IF NOT EXISTS participants (
    pid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token TEXT UNIQUE NOT NULL,
    code TEXT UNIQUE NOT NULL, pilot SMALLINT NOT NULL CHECK (pilot IN (0, 1)),
    block INTEGER NOT NULL, answers TEXT NOT NULL, submitted_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS choices (
    pid BIGINT NOT NULL REFERENCES participants(pid), block INTEGER, set_id INTEGER, kind TEXT,
    pair INTEGER, alt_id INTEGER, flipped INTEGER, chosen INTEGER, salary_level DOUBLE PRECISION,
    salary DOUBLE PRECISION, varpay TEXT, arrangement TEXT, hours INTEGER, autonomy TEXT,
    growth TEXT, rt_ms INTEGER);
"""


def _profile(row):
    return {"salary_level": float(row["salary_level"]), "varpay": row["varpay"],
            "arrangement": row["arrangement"], "hours": int(row["hours"]),
            "autonomy": row["autonomy"], "growth": row["growth"]}


def load_design(path=SURVEY / "design_blocks.csv"):
    """{block: [{1: profile, 2: profile}, ...]} with pairs in file order (pair 1..8)."""
    blocks = {}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            pair = blocks.setdefault(int(row["block"]), {}).setdefault(int(row["pair"]), {})
            pair[int(row["alt"])] = _profile(row)
    return {b: [pairs[p] for p in sorted(pairs)] for b, pairs in blocks.items()}


def load_checks(path=SURVEY / "attention_checks.csv"):
    """{screen: {"A": profile, "B": profile}}. Positions are fixed and never flipped."""
    checks = {}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            checks.setdefault(int(row["screen"]), {})[row["position"]] = _profile(row)
    return checks


def make_plan(pairs, checks, rng=RNG):
    """The 10 screens one participant sees: the block's 8 pairs shuffled into the
    design slots with random left/right, plus the two fixed checks."""
    order = list(enumerate(pairs, start=1))
    rng.shuffle(order)
    screens = []
    for set_id, (pair_no, alts) in zip(DESIGN_SLOTS, order):
        flipped = rng.random() < 0.5
        a, b = (alts[2], alts[1]) if flipped else (alts[1], alts[2])
        screens.append({"set_id": set_id, "kind": "design", "pair": pair_no,
                        "flipped": int(flipped), "A": a, "B": b})
    for set_id, sides in checks.items():
        screens.append({"set_id": set_id, "kind": "check", "pair": None,
                        "flipped": 0, "A": sides["A"], "B": sides["B"]})
    return sorted(screens, key=lambda s: s["set_id"])


def choose_block(conn, blocks, pilot, now, rng=RNG, is_postgres=False):
    """Block with the fewest completed + recently started responses; ties at random."""
    load = dict.fromkeys(blocks, 0)
    cutoff = (now - IN_PROGRESS_WINDOW).isoformat()
    placeholder = "%s" if is_postgres else "?"
    for block, n in conn.execute(
            f"SELECT block, COUNT(*) FROM sessions WHERE pilot = {placeholder} "
            f"AND (completed_at IS NOT NULL OR started_at >= {placeholder}) GROUP BY block", (pilot, cutoff)):
        load[block] = n
    least = min(load.values())
    return rng.choice(sorted(b for b, n in load.items() if n == least))


def create_app(db_path=None, database_url=None):
    """Create the application.

    Pass ``db_path`` only for local development/tests. Production uses DATABASE_URL,
    supplied by the Neon integration in Vercel's environment settings.
    """
    database_url = database_url or (None if db_path is not None else os.environ.get("DATABASE_URL"))
    is_postgres = bool(database_url)
    if is_postgres:
        try:
            import psycopg
        except ImportError as exc:  # clear error if dependencies were not installed
            raise RuntimeError("Postgres support requires psycopg; install requirements.txt") from exc
    else:
        if os.environ.get("VERCEL"):
            raise RuntimeError("DATABASE_URL must be set for this survey on Vercel")
        db_path = Path(db_path or os.environ.get("SURVEY_DB", HERE / "data" / "survey.sqlite3"))
        db_path.parent.mkdir(parents=True, exist_ok=True)
    blocks, checks = load_design(), load_checks()

    @contextmanager
    def transaction():
        conn = psycopg.connect(database_url) if is_postgres else sqlite3.connect(db_path, timeout=10)
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

    with transaction() as conn:
        if is_postgres:
            conn.execute(POSTGRES_SCHEMA)
        else:
            conn.executescript(SQLITE_SCHEMA)

    # Vercel serves public/** directly from its CDN. Keep Flask's static handler
    # for the local development server only.
    if os.environ.get("VERCEL"):
        app = Flask(__name__, static_folder=None)
    else:
        app = Flask(__name__, static_folder=str(ROOT / "public" / "static"),
                    static_url_path="/static")

    def execute(conn, sqlite_query, postgres_query, params=()):
        return conn.execute(postgres_query if is_postgres else sqlite_query, params)

    @app.get("/")
    def index():
        return send_from_directory(ROOT / "public", "index.html")

    @app.post("/api/start")
    def start():
        body = request.get_json(silent=True) or {}
        pilot = int(bool(body.get("pilot")))
        now = datetime.now(timezone.utc)
        with transaction() as conn:
            block = choose_block(conn, blocks, pilot, now, is_postgres=is_postgres)
            plan = make_plan(blocks[block], checks)
            token = secrets.token_urlsafe(16)
            execute(conn, "INSERT INTO sessions VALUES (?, ?, ?, ?, ?, NULL)",
                    "INSERT INTO sessions VALUES (%s, %s, %s, %s, %s, NULL)",
                    (token, block, pilot, json.dumps(plan), now.isoformat()))
        return jsonify(token=token, screens=plan)

    @app.post("/api/submit")
    def submit():
        body = request.get_json(silent=True)
        if not isinstance(body, dict):
            return jsonify(error="expected a JSON object"), 400
        with transaction() as conn:
            session = execute(conn,
                              "SELECT block, pilot, plan, completed_at FROM sessions WHERE token = ?",
                              "SELECT block, pilot, plan, completed_at FROM sessions WHERE token = %s",
                              (body.get("token"),)).fetchone()
            if session is None:
                return jsonify(error="unknown session"), 400
            block, pilot, plan, completed_at = session
            if completed_at:     # a retry after a lost response: hand back the same code
                (code,) = execute(conn, "SELECT code FROM participants WHERE token = ?",
                                  "SELECT code FROM participants WHERE token = %s",
                                  (body["token"],)).fetchone()
                return jsonify(code=code)
            try:
                answers, rows = validate(body, json.loads(plan))
            except Invalid as e:
                return jsonify(error=str(e)), 400
            code = _new_code(conn, is_postgres=is_postgres)
            now = datetime.now(timezone.utc).isoformat()
            if is_postgres:
                pid = conn.execute(
                    "INSERT INTO participants (token, code, pilot, block, answers, submitted_at) "
                    "VALUES (%s, %s, %s, %s, %s, %s) RETURNING pid",
                    (body["token"], code, pilot, block, json.dumps(answers), now)).fetchone()[0]
                conn.executemany(
                    "INSERT INTO choices VALUES (%(pid)s, %(block)s, %(set_id)s, %(kind)s, %(pair)s, "
                    "%(alt_id)s, %(flipped)s, %(chosen)s, %(salary_level)s, %(salary)s, %(varpay)s, "
                    "%(arrangement)s, %(hours)s, %(autonomy)s, %(growth)s, %(rt_ms)s)",
                    [dict(r, pid=pid, block=block) for r in rows])
            else:
                pid = conn.execute(
                    "INSERT INTO participants (token, code, pilot, block, answers, submitted_at) "
                    "VALUES (?, ?, ?, ?, ?, ?)",
                    (body["token"], code, pilot, block, json.dumps(answers), now)).lastrowid
                conn.executemany(
                    "INSERT INTO choices VALUES (:pid, :block, :set_id, :kind, :pair, :alt_id, :flipped, "
                    ":chosen, :salary_level, :salary, :varpay, :arrangement, :hours, :autonomy, :growth, :rt_ms)",
                    [dict(r, pid=pid, block=block) for r in rows])
            execute(conn, "UPDATE sessions SET completed_at = ? WHERE token = ?",
                    "UPDATE sessions SET completed_at = %s WHERE token = %s", (now, body["token"]))
        return jsonify(code=code)

    @app.get("/api/export.zip")
    def export_zip():
        expected = os.environ.get("EXPORT_TOKEN", "")
        given = request.headers.get("Authorization", "").removeprefix("Bearer ")
        if not expected or not secrets.compare_digest(given, expected):
            abort(404)
        buf = io.BytesIO()
        with transaction() as conn, zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            for name, text in csv_texts(conn).items():
                z.writestr(name, text)
        return Response(buf.getvalue(), mimetype="application/zip",
                        headers={"Content-Disposition": "attachment; filename=survey_export.zip"})

    return app


def _new_code(conn, is_postgres=False):
    while True:
        code = "".join(RNG.choice(CODE_ALPHABET) for _ in range(6))
        placeholder = "%s" if is_postgres else "?"
        if not conn.execute(f"SELECT 1 FROM participants WHERE code = {placeholder}", (code,)).fetchone():
            return code


app = create_app()


if __name__ == "__main__":
    app.run(port=int(os.environ.get("PORT", 5050)), debug=False)
